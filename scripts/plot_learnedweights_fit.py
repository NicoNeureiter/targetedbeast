#!/usr/bin/env python3
"""
Plot LearnedWeights fit correlations from the CSV generated by LearnedWeightsFitCli.

Usage:
  python plot_learnedweights_fit.py --csv learnedweights-iecor.weights.csv --out learnedweights-iecor.scatter.png
"""

import argparse
import csv
import math
import random
from typing import List, Tuple

import numpy as np
from scipy.special import logit
import matplotlib.pyplot as plt


def pearson(x: List[float], y: List[float]) -> float:
    if len(x) != len(y) or not x:
        return float("nan")
    mx = sum(x) / len(x)
    my = sum(y) / len(y)
    sxy = 0.0
    sxx = 0.0
    syy = 0.0
    for a, b in zip(x, y):
        dx = a - mx
        dy = b - my
        sxy += dx * dy
        sxx += dx * dx
        syy += dy * dy
    denom = math.sqrt(sxx * syy)
    return float("nan") if denom == 0.0 else sxy / denom


def load_rows(csv_file: str) -> Tuple[List[float], List[float], List[float]]:
    target, learned, pca = [], [], []
    with open(csv_file, "r", newline="") as f:
        reader = csv.DictReader(f)
        for row in reader:
            target.append(float(row["target"]))
            learned.append(float(row["predLearned"]))
            pca.append(float(row["predPca"]))
    return target, learned, pca


def maybe_subsample(*arrays: List[float], max_points: int, seed: int):
    n = len(arrays[0])
    if n <= max_points:
        return arrays
    rng = random.Random(seed)
    idx = list(range(n))
    rng.shuffle(idx)
    idx = idx[:max_points]
    idx.sort()
    out = []
    for arr in arrays:
        out.append([arr[i] for i in idx])
    return out


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--csv", required=True, help="weights CSV from fit-report")
    parser.add_argument("--out", default="learnedweights-fit.scatter.png", help="output PNG")
    parser.add_argument("--max-points", type=int, default=20000, help="max points to plot")
    parser.add_argument("--seed", type=int, default=1, help="random seed for subsampling")
    args = parser.parse_args()

    target, learned, pca = load_rows(args.csv)
    target, learned, pca = maybe_subsample(target, learned, pca, max_points=args.max_points, seed=args.seed)

    r_learned = pearson(target, learned)
    r_pca = pearson(target, pca)

    fig, axes = plt.subplots(1, 2, figsize=(11, 5), sharex=True, sharey=False)

    axes[0].scatter((target), (learned), s=6, alpha=0.25)
    axes[0].set_title(f"Learned vs Target (r={r_learned:.3f})")
    axes[0].set_xlabel("Target probability")
    axes[0].set_ylabel("Predicted probability")

    print(pca)
    axes[1].scatter((target), np.log(0.000001 + np.array(pca)), s=6, alpha=0.25)
    axes[1].set_title(f"PCA vs Target (r={r_pca:.3f})")
    axes[1].set_xlabel("Target probability")

    for ax in axes:
        ax.grid(True, alpha=0.25)

    fig.tight_layout()
    fig.savefig(args.out, dpi=160)
    print(f"Saved {args.out}")


if __name__ == "__main__":
    main()
